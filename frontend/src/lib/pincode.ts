// Explicit non-COD postal codes (remote mountain/island circles)
export const NON_COD_PINCODES = new Set<string>([
  '194101', '194102', '194103', '194104', '194105', '194106',
  '744101', '744102', '744103', '744104', '744202', '744301',
  '791001', '795001', '796001', '797001', '799001',
]);

/**
 * Evaluates any 6-digit Indian pincode to determine delivery fees,
 * city, state, estimated transit time, and COD eligibility.
 */
export function evaluatePincode(pincode: string): PincodeCheckResult {
  const cleanPin = (pincode || '').trim().replace(/\D/g, '');

  if (cleanPin.length !== 6 || cleanPin.startsWith('0')) {
    return {
      pincode: cleanPin,
      isServiceable: false,
      serviceable: false,
      isSupported: false,
      codAvailable: false,
      shippingFee: 90,
      deliveryCharge: 90,
      charge: 90,
      freeShippingAbove: 999,
      isFreeDelivery: false,
      estimatedDeliveryDays: 'N/A',
      estimatedDays: 'N/A',
      regionName: 'Invalid PIN Code',
      areaName: 'Invalid PIN Code',
      zoneName: 'Invalid PIN Code',
      city: '',
      state: '',
      district: '',
      message: 'Please enter a valid 6-digit Indian postal code (e.g. 190001, 110001, 560001).',
    };
  }

  const isExplicitNonCod = NON_COD_PINCODES.has(cleanPin);

  // Match rules by longest prefix first
  let matchedRule: PincodeRule | null = null;
  const sortedRules = [...INDIAN_PINCODE_RULES].sort(
    (a, b) => (b.pincodePrefix?.length || 0) - (a.pincodePrefix?.length || 0)
  );

  for (const rule of sortedRules) {
    if (rule.pincodes && rule.pincodes.includes(cleanPin)) {
      matchedRule = rule;
      break;
    }
    if (rule.pincodePrefix && cleanPin.startsWith(rule.pincodePrefix)) {
      matchedRule = rule;
      break;
    }
  }

  const activeRule = matchedRule || DEFAULT_REST_OF_INDIA_RULE;
  const finalCodAvailable = isExplicitNonCod ? false : activeRule.codAvailable;
  const fee = activeRule.shippingFee;
  const threshold = activeRule.freeShippingAbove || 999;

  return {
    pincode: cleanPin,
    isServiceable: true,
    serviceable: true,
    isSupported: true,
    codAvailable: finalCodAvailable,
    shippingFee: fee,
    deliveryCharge: fee,
    charge: fee,
    freeShippingAbove: threshold,
    isFreeDelivery: fee === 0,
    estimatedDeliveryDays: activeRule.estimatedDeliveryDays,
    estimatedDays: activeRule.estimatedDeliveryDays,
    regionName: activeRule.regionName,
    areaName: activeRule.regionName,
    zoneName: activeRule.regionName,
    city: activeRule.city,
    state: activeRule.state,
    district: activeRule.district,
    message: finalCodAvailable
      ? `Delivery available for ${activeRule.regionName} (${activeRule.estimatedDeliveryDays}). Cash on Delivery is enabled.`
      : `Delivery available for ${activeRule.regionName} (${activeRule.estimatedDeliveryDays}). Prepaid only via Cards/UPI (COD unavailable in this circle).`,
  };
}

export const checkPincode = evaluatePincode;
export const DEFAULT_PINCODE_RULES = INDIAN_PINCODE_RULES;
